"""Builds the offline preview of Kernel Lab into preview/out/.

The hosted preview runs in a sandbox: no internet, relative paths only, and
the page body is wrapped in its own <html> skeleton. This turns
site/kernel/index.html into that shape and copies the files it needs.

    python3 preview/build.py
"""
import os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
OUT = os.path.join(ROOT, "preview", "out")

# Artifacts only serve web file types, so the BIOS and disk images travel
# base64-encoded inside images.js instead of as .bin/.img files.
FILES = {
    "v86/libv86.js": "v86/libv86.js", "v86/v86.wasm": "v86/v86.wasm",
    "meteo/countries.geo.json": "meteo/countries.geo.json",
    "kernel/smartestchild.js": "kernel/smartestchild.js", "kernel/hostlink.js": "kernel/hostlink.js",
}


def write_images():
    """Packs every binary the page boots (BIOS, ConMon, run v86 guests) into
    images.js. Trailing zero bytes are dropped and restored on decode."""
    import base64
    files = {
        "seabios.bin": "v86/seabios.bin", "vgabios.bin": "v86/vgabios.bin",
        "conmon.bin": "kernels/conmon.bin", "hello-floppy.img": "kernels/hello-floppy.img",
    }
    for f in sorted(os.listdir(os.path.join(SITE, "guests"))):
        if f.endswith((".img", ".flp")):
            files[f] = "guests/" + f
    entries = []
    for name, rel in files.items():
        data = open(os.path.join(SITE, rel), "rb").read()
        body = data.rstrip(b"\0")
        entries.append(f'    "{name}": [{len(data)}, "{base64.b64encode(body).decode()}"],')
    js = "\n".join([
        "// Generated by preview/build.py: BIOS, kernel and disk images for the offline preview.",
        "(() => {",
        "  const PACKED = {", *entries, "  };",
        "  const cache = {};",
        "  window.CONMON_IMAGES = {",
        "    has: (name) => Object.prototype.hasOwnProperty.call(PACKED, name),",
        "    get(name) {",
        "      if (!cache[name]) {",
        "        const [size, b64] = PACKED[name], s = atob(b64), u = new Uint8Array(size);",
        "        for (let i = 0; i < s.length; i++) u[i] = s.charCodeAt(i);",
        "        cache[name] = u.buffer;",
        "      }",
        "      return cache[name].slice(0);",
        "    },",
        "  };",
        "})();", ""])
    open(os.path.join(OUT, "images.js"), "w").write(js)


def main():
    shutil.rmtree(OUT, ignore_errors=True)
    for dst, src in FILES.items():
        os.makedirs(os.path.dirname(os.path.join(OUT, dst)), exist_ok=True)
        shutil.copyfile(os.path.join(SITE, src), os.path.join(OUT, dst))

    # Absolute paths -> relative ones.
    hl = open(os.path.join(OUT, "kernel/hostlink.js")).read().replace('"/meteo/countries.geo.json"', '"meteo/countries.geo.json"')
    open(os.path.join(OUT, "kernel/hostlink.js"), "w").write(hl)
    kj = open(os.path.join(SITE, "kernel/kernel.js")).read()
    for a in ["/kernels/", "/v86/"]:
        kj = kj.replace('"' + a, '"' + a[1:])
    write_images()
    open(os.path.join(OUT, "kernel/kernel.js"), "w").write(kj)
    shutil.copyfile(os.path.join(ROOT, "preview", "preview-data.js"), os.path.join(OUT, "preview-data.js"))

    page = open(os.path.join(SITE, "kernel/index.html")).read()
    head = page[page.index("<head>") + 6: page.index("</head>")]
    body = page[page.index("<body>") + 6: page.index("</body>")]
    css = open(os.path.join(SITE, "assets/style.css")).read()
    # Single dark look; side gutters clear a phone's system bars.
    css = css.replace(":root {", ":root {\n  color-scheme: dark;", 1)
    css = css.replace(".wrap { max-width: 1100px; margin: 0 auto; padding: 0 16px; }",
                      ".wrap { max-width: 1100px; margin: 0 auto; padding-left: max(16px, env(safe-area-inset-left, 0px)); padding-right: max(16px, env(safe-area-inset-right, 0px)); }")
    css = css.replace(".topbar { border-bottom:", ".topbar { top: env(safe-area-inset-top, 0px) !important; border-bottom:", 1)
    css += "\nbody::before { content: \"\"; position: fixed; inset: 0 0 auto; height: env(safe-area-inset-top, 0px); z-index: 10; background: var(--bg); }\n"
    css += ".preview-note { border: 1px solid rgba(251,191,36,.4); background: rgba(251,191,36,.07); color: #fde68a; border-radius: 10px; padding: 10px 12px; font-size: 14px; line-height: 1.45; max-width: 760px; margin-top: 14px; }\n"
    css += ".preview-note b { color: #fff3c4; }\n"

    head_styles = "".join(re.findall(r"<style>.*?</style>", head, re.S))
    fonts = "\n".join(l.strip() for l in head.splitlines() if "fonts.g" in l)

    body = re.sub(r'<nav class="nav">.*?</nav>', '<span class="badge" style="margin-left:auto"><span class="led"></span>preview</span>', body, flags=re.S)
    body = body.replace('<a class="brand" href="/">', '<span class="brand">').replace('ConMon<span class="full">&nbsp;Lab</span></a>', 'ConMon<span class="full">&nbsp;Lab</span></span>')
    body = re.sub(r'<footer class="wrap footer">.*?</footer>', '<footer class="wrap footer">ConMon Lab preview. The full site, with the YouTube Test app, lives on your Netlify deploy.</footer>', body, flags=re.S)
    note = ('<div class="preview-note"><b>Preview mode.</b> This copy runs without internet, so the AI chat offers '
            'SmartestChild only, and solMeteo shows <b>sample</b> weather for 47 big cities (try Rome, Tokyo, New York). '
            'Everything else is the real ConMon, including <b>run v86</b>, which opens MikeOS, Tetros and more in a window. '
            'On your Netlify site, Transformers.js, WebLLM, Ollama, live Open-Meteo weather and mp finder\'s live stats all work.</div>')
    body = body.replace("</p>\n    </section>", "</p>\n      " + note + "\n    </section>", 1)
    scripts = ('<script src="preview-data.js"></script>\n  <script src="images.js"></script>\n  <script src="v86/libv86.js"></script>\n'
               '  <script src="kernel/smartestchild.js"></script>\n  <script src="kernel/hostlink.js"></script>\n'
               '  <script src="kernel/kernel.js"></script>')
    body = re.sub(r'<script src="/v86/libv86.js"></script>.*<script src="/kernel/kernel.js"></script>', scripts, body, flags=re.S)
    assert 'src="/' not in body and 'href="/' not in body, "absolute path left in preview page"

    out = ("<title>ConMon Kernel Lab</title>\n"
           '<meta name="claude:viewport-fit-sides" content="cover">\n'
           f"{fonts}\n<style>\n{css}\n</style>\n{head_styles}\n{body}")
    open(os.path.join(OUT, "index.html"), "w").write(out)
    print("preview built:", OUT)


if __name__ == "__main__":
    main()
